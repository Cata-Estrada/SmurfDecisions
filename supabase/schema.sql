-- 1. Tabla: fuentes
CREATE TABLE IF NOT EXISTS public.fuentes (
    id TEXT PRIMARY KEY,
    nombre TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('indicador', 'noticia')),
    frecuencia_horas INTEGER NOT NULL DEFAULT 24
);

-- 2. Tabla: indicadores
CREATE TABLE IF NOT EXISTS public.indicadores (
    codigo TEXT PRIMARY KEY,
    nombre TEXT NOT NULL,
    unidad TEXT NOT NULL
);

-- 3. Tabla: valores_indicador
CREATE TABLE IF NOT EXISTS public.valores_indicador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicador_codigo TEXT NOT NULL REFERENCES public.indicadores(codigo) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    valor NUMERIC(12, 4) NOT NULL,
    fuente TEXT NOT NULL,
    capturado_en TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_indicador_fecha UNIQUE (indicador_codigo, fecha)
);

-- 4. Tabla: reglas
CREATE TABLE IF NOT EXISTS public.reglas (
    tipo_evento TEXT PRIMARY KEY,
    accion TEXT NOT NULL,
    area_responsable TEXT NOT NULL,
    supuestos TEXT NOT NULL
);

-- 5. Tabla: alertas
CREATE TABLE IF NOT EXISTS public.alertas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    resumen TEXT NOT NULL,
    enlace TEXT NOT NULL UNIQUE,
    fuente TEXT NOT NULL,
    fecha_publicacion DATE NOT NULL,
    factor TEXT NOT NULL CHECK (factor IN ('Político', 'Económico', 'Social', 'Tecnológico', 'Ecológico', 'Legal')),
    area TEXT NOT NULL CHECK (area IN ('Compras y finanzas', 'Operaciones y logística', 'Forestal', 'Talento humano', 'Jurídico y ambiental', 'Planeación y sostenibilidad', 'Comercial')),
    tipo_evento TEXT NOT NULL REFERENCES public.reglas(tipo_evento) ON UPDATE CASCADE ON DELETE RESTRICT,
    probabilidad INTEGER NOT NULL CHECK (probabilidad BETWEEN 1 AND 5),
    impacto INTEGER NOT NULL CHECK (impacto BETWEEN 1 AND 5),
    puntaje INTEGER NOT NULL CHECK (puntaje BETWEEN 1 AND 25),
    nivel TEXT NOT NULL CHECK (nivel IN ('Alto', 'Medio', 'Bajo')),
    prioritaria BOOLEAN NOT NULL DEFAULT false,
    estado TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'validada', 'descartada', 'sin_clasificar')),
    decision TEXT NOT NULL DEFAULT 'pendiente' CHECK (decision IN ('pendiente', 'aceptada', 'descartada')),
    origen TEXT NOT NULL DEFAULT 'n8n' CHECK (origen IN ('n8n', 'base')),
    explicacion TEXT NOT NULL DEFAULT '',
    creada_en TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 6. Tabla: ejecuciones
CREATE TABLE IF NOT EXISTS public.ejecuciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flujo TEXT NOT NULL,
    fuente TEXT NOT NULL,
    inicio TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    fin TIMESTAMPTZ,
    estado TEXT NOT NULL CHECK (estado IN ('ok', 'error')),
    registros_nuevos INTEGER NOT NULL DEFAULT 0,
    mensaje_error TEXT
);

-- ==============================================================================
-- ÍNDICES PARA OPTIMIZAR CONSULTAS DEL APLICATIVO Y N8N
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_valores_indicador_codigo_fecha ON public.valores_indicador (indicador_codigo, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_alertas_factor ON public.alertas (factor);
CREATE INDEX IF NOT EXISTS idx_alertas_estado ON public.alertas (estado);
CREATE INDEX IF NOT EXISTS idx_alertas_prioritaria ON public.alertas (prioritaria);
CREATE INDEX IF NOT EXISTS idx_alertas_fecha ON public.alertas (fecha_publicacion DESC);
CREATE INDEX IF NOT EXISTS idx_alertas_tipo_evento ON public.alertas (tipo_evento);
CREATE INDEX IF NOT EXISTS idx_ejecuciones_inicio ON public.ejecuciones (inicio DESC);

-- ==============================================================================
-- POLÍTICAS DE SEGURIDAD (RLS)
-- Nota: Según el alcance documentado del MVP (sección 6 del documento maestro),
-- el prototipo utiliza solo la clave pública anónima sin inicio de sesión ni roles.
-- ==============================================================================
ALTER TABLE public.fuentes DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.indicadores DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.valores_indicador DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.reglas DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.alertas DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.ejecuciones DISABLE ROW LEVEL SECURITY;
